// Helper functions for State and District manipulation

/**
 * Returns all configured States
 */
export const getAllStates = () => {
  return STATES_DISTRICTS_DATA.map((s) => ({
    code: s.code,
    name: s.name,
    treasury_address: s.treasury_address,
    districtsCount: s.districts.length
  }));
};

/**
 * Find State object by code or name
 */
export const getState = (stateCodeOrName) => {
  if (!stateCodeOrName) return null;
  const query = stateCodeOrName.trim().toUpperCase();
  return (
    STATES_DISTRICTS_DATA.find(
      (s) => s.code.toUpperCase() === query || s.name.toUpperCase() === query
    ) || null
  );
};

/**
 * Returns ONLY the districts for the specified State.
 * Returns empty array if state is invalid or empty.
 */
export const getDistrictsByState = (stateCodeOrName) => {
  if (!stateCodeOrName) return [];
  const state = getState(stateCodeOrName);
  if (!state) return [];
  return state.districts.map((name) => ({
    name,
    state_code: state.code,
    state_name: state.name
  }));
};

/**
 * Check if a district belongs to a given state
 */
export const isValidDistrictForState = (districtName, stateCodeOrName) => {
  if (!districtName || !stateCodeOrName) return false;
  const districts = getDistrictsByState(stateCodeOrName);
  const normalizedDistrict = districtName.trim().toLowerCase();
  return districts.some(
    (d) =>
      d.name.toLowerCase() === normalizedDistrict ||
      d.name.toLowerCase().includes(normalizedDistrict) ||
      normalizedDistrict.includes(d.name.toLowerCase())
  );
};

/**
 * Find the parent State for a given district name
 */
export const getStateForDistrict = (districtName) => {
  if (!districtName) return null;
  const normalized = districtName.trim().toLowerCase();
  for (const s of STATES_DISTRICTS_DATA) {
    const match = s.districts.find(
      (d) =>
        d.toLowerCase() === normalized ||
        d.toLowerCase().includes(normalized) ||
        normalized.includes(d.toLowerCase())
    );
    if (match) {
      return { code: s.code, name: s.name };
    }
  }
  return null;
};
